// Isolated PostgreSQL validation. Install @electric-sql/pglite separately, or pass
// its dist/index.js path: node scripts/test-producer-notebook-rewards.mjs <path>
import assert from "node:assert/strict";
import { readFile, mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";

const { PGlite } = await import(process.argv[2] ? pathToFileURL(path.resolve(process.argv[2])).href : "@electric-sql/pglite");
const db = new PGlite();
const ids = Object.fromEntries(["alice", "bob", "guest", "unverified", "overflow"].map((name, index) => [name, `00000000-0000-4000-8000-${String(index + 1).padStart(12, "0")}`]));
const checks = [];
const query = (sql, args = []) => db.query(sql, args);
const exec = (sql) => db.exec(sql);
const scalar = async (sql, args = []) => Object.values((await query(sql, args)).rows[0])[0];
const read = (file) => readFile(path.resolve(file), "utf8");
const check = (name, actual, expected) => { assert.deepEqual(actual, expected, name); checks.push(name); };
const call = (functionName, user, producer = "producer-one") => scalar(`SELECT public.${functionName}($1,$2)`, [ids[user] ?? user, producer]);
const progress = async (user) => (await scalar("SELECT public.rpc_kq_get_producer_notebook_progress($1)", [ids[user]])).find((row) => row.producerId === "producer-one");
const reject = async (name, operation, message) => {
  await assert.rejects(operation, (error) => error.message === message, name);
  checks.push(name);
};

try {
  await exec(`
    CREATE SCHEMA auth; CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role;
    CREATE TABLE auth.users(id UUID PRIMARY KEY,email TEXT,email_confirmed_at TIMESTAMPTZ);
    CREATE TABLE producers(id TEXT PRIMARY KEY,name TEXT NOT NULL);
    CREATE TABLE products(id TEXT PRIMARY KEY,category TEXT NOT NULL);
    CREATE TABLE contest_seasons(id TEXT PRIMARY KEY,label TEXT NOT NULL,is_active BOOLEAN NOT NULL,is_archived BOOLEAN NOT NULL,
      year INTEGER NOT NULL,harvest_end DATE,created_at TIMESTAMPTZ NOT NULL DEFAULT now());
    CREATE TABLE contest_entries(id TEXT PRIMARY KEY,product_id TEXT REFERENCES products,producer_id TEXT REFERENCES producers,
      season_id TEXT REFERENCES contest_seasons,is_published BOOLEAN NOT NULL,track TEXT NOT NULL);
    CREATE TABLE contest_reviews(id UUID PRIMARY KEY DEFAULT gen_random_uuid(),entry_id TEXT REFERENCES contest_entries,
      customer_id UUID REFERENCES auth.users,status TEXT NOT NULL,UNIQUE(entry_id,customer_id));
    CREATE TABLE orders(id TEXT PRIMARY KEY,customer_id UUID REFERENCES auth.users,customer_email TEXT,payment_state TEXT,
      status TEXT,created_at TIMESTAMPTZ NOT NULL DEFAULT now());
    CREATE TABLE order_items(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,order_id TEXT REFERENCES orders,
      product_id TEXT NOT NULL,quantity INTEGER NOT NULL);
    CREATE TYPE lottery_card_rarity AS ENUM('common','silver','gold','epic','legendary');
    CREATE TABLE lottery_card_collections(id UUID PRIMARY KEY DEFAULT gen_random_uuid(),code TEXT UNIQUE,is_active BOOLEAN);
    CREATE TABLE lottery_card_definitions(id UUID PRIMARY KEY DEFAULT gen_random_uuid(),collection_id UUID REFERENCES lottery_card_collections,
      code TEXT UNIQUE,name TEXT,rarity lottery_card_rarity,image_url TEXT DEFAULT '',card_number INTEGER,is_active BOOLEAN);
    CREATE TABLE lottery_card_instances(id UUID PRIMARY KEY DEFAULT gen_random_uuid(),user_id UUID REFERENCES auth.users,
      card_definition_id UUID REFERENCES lottery_card_definitions,ticket_id UUID,kq_support_entitlement_id UUID,
      source_bot_battle_id UUID,pioneer_grant_id UUID,pack_slot INTEGER CHECK(pack_slot BETWEEN 1 AND 13),
      CONSTRAINT lottery_card_instances_source_required CHECK(ticket_id IS NOT NULL OR kq_support_entitlement_id IS NOT NULL
        OR source_bot_battle_id IS NOT NULL OR pioneer_grant_id IS NOT NULL));
    CREATE TABLE kq_equipment_wallets(user_id UUID PRIMARY KEY REFERENCES auth.users,cash_cents INTEGER NOT NULL DEFAULT 35000 CHECK(cash_cents>=0),updated_at TIMESTAMPTZ DEFAULT now());
    CREATE TABLE kq_heritage_card_definitions(code TEXT PRIMARY KEY,rarity TEXT,is_active BOOLEAN);
    CREATE TABLE kq_producer_reward_campaigns(id UUID PRIMARY KEY DEFAULT gen_random_uuid(),producer_id TEXT REFERENCES producers,
      heritage_code TEXT REFERENCES kq_heritage_card_definitions,status TEXT);
    CREATE TABLE kq_producer_reward_entries(campaign_id UUID REFERENCES kq_producer_reward_campaigns,entry_id TEXT REFERENCES contest_entries,PRIMARY KEY(campaign_id,entry_id));
    CREATE TABLE kq_heritage_draws(id UUID PRIMARY KEY DEFAULT gen_random_uuid(),user_id UUID REFERENCES auth.users,order_item_id BIGINT,
      unit_index INTEGER,card_code TEXT,rarity TEXT,seed INTEGER,was_duplicate BOOLEAN,source TEXT,craft_key TEXT,producer_campaign_id UUID);
    CREATE UNIQUE INDEX heritage_campaign_user ON kq_heritage_draws(user_id,producer_campaign_id) WHERE source='producer_notebook';
    CREATE TABLE kq_producer_heritage_reward_grants(id UUID PRIMARY KEY DEFAULT gen_random_uuid(),user_id UUID REFERENCES auth.users,
      campaign_id UUID REFERENCES kq_producer_reward_campaigns,producer_id TEXT,heritage_code TEXT,heritage_draw_id UUID REFERENCES kq_heritage_draws,
      UNIQUE(user_id,campaign_id));
    CREATE TABLE kq_notebook_flower_reward_grants(id UUID PRIMARY KEY,receipt JSONB);
    CREATE TABLE kq_notebook_flower_reward_packs(id UUID PRIMARY KEY,receipt JSONB);
    CREATE TABLE kq_support_booster_entitlements(id UUID PRIMARY KEY,receipt JSONB);
    INSERT INTO kq_notebook_flower_reward_grants VALUES(gen_random_uuid(),' {"historical":true}');
    INSERT INTO kq_notebook_flower_reward_packs VALUES(gen_random_uuid(),' {"historical":true}');
    INSERT INTO kq_support_booster_entitlements VALUES(gen_random_uuid(),' {"historical":true}');
    CREATE FUNCTION lottery_secure_random_int(p_min INTEGER,p_max INTEGER) RETURNS INTEGER LANGUAGE sql AS $$ SELECT p_min $$;
  `);
  // Exercise the actual balanced-journal implementation. Only the unrelated
  // equipment/stock opening valuation and RNG entropy are replaced by fixtures.
  const treasury = await read("supabase/migrations/20260921000200_kq_treasury_accounting.sql");
  await exec(treasury.split("-- Actual production cost only.")[0] + "COMMIT;");
  await exec(`
    CREATE FUNCTION kq_treasury_initialize(p_user UUID) RETURNS VOID LANGUAGE plpgsql AS $$ BEGIN
      INSERT INTO kq_treasury_accounts(user_id) VALUES(p_user) ON CONFLICT DO NOTHING;
      PERFORM kq_treasury_pair(p_user,'opening','opening',now(),'cash','opening_equity',
        (SELECT cash_cents FROM kq_equipment_wallets WHERE user_id=p_user));
    END $$;
    CREATE FUNCTION test_wallet_observer() RETURNS TRIGGER LANGUAGE plpgsql AS $$ BEGIN
      IF TG_OP='INSERT' THEN PERFORM kq_treasury_initialize(NEW.user_id);
      ELSE PERFORM kq_treasury_pair(NEW.user_id,'cash-movement','cash:'||gen_random_uuid(),now(),'cash','suspense',NEW.cash_cents::BIGINT-OLD.cash_cents); END IF;
      RETURN NULL;
    END $$;
    CREATE TRIGGER test_wallet_observer AFTER INSERT OR UPDATE OF cash_cents ON kq_equipment_wallets FOR EACH ROW EXECUTE FUNCTION test_wallet_observer();
  `);
  for (const [name, id] of Object.entries(ids)) {
    await query("INSERT INTO auth.users VALUES($1,$2,$3)", [id, name === "unverified" ? "guest@example.test" : `${name}@example.test`, name === "unverified" ? null : new Date()]);
  }
  await exec(`
    INSERT INTO producers VALUES('producer-one','Le producteur'),('producer-empty','Sans fleur'),('producer-two','Autre ferme');
    INSERT INTO products VALUES('flower-a','fleurs'),('flower-b','fleurs'),('hidden','fleurs'),('old-flower','fleurs'),('oil','huiles'),('other-flower','fleurs');
    INSERT INTO contest_seasons(id,label,is_active,is_archived,year) VALUES('current','Saison actuelle',true,false,2026),('old','Archive',false,true,2025);
    INSERT INTO contest_entries VALUES
      ('a-regular','flower-a','producer-one','current',true,'regular'),('a-contest','flower-a','producer-one','current',true,'concours'),
      ('b-regular','flower-b','producer-one','current',true,'regular'),('hidden','hidden','producer-one','current',false,'concours'),
      ('oil','oil','producer-one','current',true,'regular'),('old-flower','old-flower','producer-one','old',true,'regular'),
      ('old-b','flower-b','producer-one','old',true,'regular'),('other','other-flower','producer-two','current',true,'regular');
    INSERT INTO lottery_card_collections(code,is_active) VALUES('HEMP_HEROES_2026',true),('OTHER',true);
    INSERT INTO lottery_card_definitions(collection_id,code,name,rarity,card_number,is_active)
      SELECT id,'HH2026-001','Legendary','legendary',1,true FROM lottery_card_collections WHERE code='HEMP_HEROES_2026';
    INSERT INTO lottery_card_definitions(collection_id,code,name,rarity,card_number,is_active)
      SELECT id,'HH2026-005','Gold','gold',5,true FROM lottery_card_collections WHERE code='HEMP_HEROES_2026';
    INSERT INTO lottery_card_definitions(collection_id,code,name,rarity,card_number,is_active)
      SELECT id,'HH2026-010','Silver','silver',10,true FROM lottery_card_collections WHERE code='HEMP_HEROES_2026';
    INSERT INTO lottery_card_definitions(collection_id,code,name,rarity,card_number,is_active)
      SELECT id,'HH2026-006','Inactive gold','gold',4,false FROM lottery_card_collections WHERE code='HEMP_HEROES_2026';
    INSERT INTO lottery_card_definitions(collection_id,code,name,rarity,card_number,is_active)
      SELECT id,'OTHER-001','Other gold','gold',1,true FROM lottery_card_collections WHERE code='OTHER';
    INSERT INTO kq_heritage_card_definitions VALUES('HERITAGE-001','common',true);
    INSERT INTO kq_producer_reward_campaigns(producer_id,heritage_code,status) VALUES('producer-one','HERITAGE-001','active');
    INSERT INTO kq_producer_reward_entries SELECT id,'a-contest' FROM kq_producer_reward_campaigns;
  `);
  const historyBefore = await scalar("SELECT jsonb_build_array((SELECT jsonb_agg(t) FROM kq_notebook_flower_reward_grants t),(SELECT jsonb_agg(t) FROM kq_notebook_flower_reward_packs t),(SELECT jsonb_agg(t) FROM kq_support_booster_entitlements t))");
  await exec(await read("supabase/migrations/20260925000200_kq_producer_tasting_completion.sql"));

  check("current-season, published flower requirements deduplicate tracks", (await progress("alice")).qualifyingProductIds, ["flower-a", "flower-b"]);
  check("read-only progress creates no wallet", await scalar("SELECT count(*)::INTEGER FROM kq_equipment_wallets"), 0);
  await reject("empty producer cannot earn a reward", () => call("rpc_kq_claim_producer_completion", "alice", "producer-empty"), "kq_producer_completion_incomplete");
  await reject("unknown user rejected", () => call("rpc_kq_claim_producer_completion", "00000000-0000-4000-8000-999999999999"), "kq_producer_completion_invalid");
  await query("INSERT INTO contest_reviews(entry_id,customer_id,status) VALUES('a-contest',$1,'approved'),('b-regular',$1,'pending'),('old-b',$1,'approved')", [ids.alice]);
  const firstReview = await scalar("SELECT id FROM contest_reviews WHERE entry_id='a-contest' AND customer_id=$1", [ids.alice]);
  const firstReward = await scalar("SELECT rpc_kq_grant_producer_notebook_rewards($1,$2)", [ids.alice, firstReview]);
  check("first approved contest tasting retains Heritage", firstReward.heritageGranted, 1);
  check("contest tasting creates no new packs", firstReward.flowerBoostersGranted, 0);
  check("old crop does not satisfy current second flower", (await progress("alice")).reviewedProductIds, ["flower-a"]);
  await reject("partial approved notebook cannot claim", () => call("rpc_kq_claim_producer_completion", "alice"), "kq_producer_completion_incomplete");
  check("incomplete claims leave no grant", await scalar("SELECT count(*)::INTEGER FROM kq_producer_completion_grants"), 0);
  await query("UPDATE contest_reviews SET status='approved' WHERE entry_id='b-regular' AND customer_id=$1", [ids.alice]);
  const secondReview = await scalar("SELECT id FROM contest_reviews WHERE entry_id='b-regular' AND customer_id=$1", [ids.alice]);
  const completed = await scalar("SELECT rpc_kq_grant_producer_notebook_rewards($1,$2)", [ids.alice, secondReview]);
  check("Regular tasting completes the same producer reward", [completed.completionGranted, completed.cashCents], [true, 10000]);
  check("wallet receives exactly 100 euros", await scalar("SELECT cash_cents FROM kq_equipment_wallets WHERE user_id=$1", [ids.alice]), 45000);
  check("journal records reward revenue", await scalar("SELECT balance_cents FROM kq_treasury_balances WHERE user_id=$1 AND account='revenue_rewards'", [ids.alice]), -10000);
  check("reward accounting clears suspense", await scalar("SELECT balance_cents FROM kq_treasury_balances WHERE user_id=$1 AND account='suspense'", [ids.alice]), 0);
  const repeated = await Promise.all(Array.from({ length: 6 }, () => call("rpc_kq_claim_producer_completion", "alice")));
  check("parallel completion retries replay one grant", repeated.every((result) => result.alreadyGranted), true);
  check("parallel retries do not credit again", await scalar("SELECT cash_cents FROM kq_equipment_wallets WHERE user_id=$1", [ids.alice]), 45000);
  check("Heritage remains unique after approval retries", (await scalar("SELECT rpc_kq_grant_producer_notebook_rewards($1,$2)", [ids.alice, firstReview])).heritageGranted, 0);
  await exec("UPDATE contest_entries SET is_published=true WHERE id='hidden'");
  check("new products do not reset lifetime completion", (await call("rpc_kq_claim_producer_completion", "alice")).qualifyingProductIds, ["flower-a", "flower-b"]);
  await exec("UPDATE contest_entries SET is_published=false WHERE id='hidden'");

  async function order(id, owner, state, status, items, email, createdAt) {
    await query("INSERT INTO orders(id,customer_id,customer_email,payment_state,status,created_at) VALUES($1,$2,$3,$4,$5,COALESCE($6,now()))", [id, owner ? ids[owner] : null, email ?? (owner ? `${owner}@example.test` : null), state, status, createdAt ?? null]);
    for (const [product, quantity] of items) await query("INSERT INTO order_items(order_id,product_id,quantity) VALUES($1,$2,$3)", [id, product, quantity]);
  }
  await order("a-paid", "alice", "paid", "paid", [["flower-a::3g", 1]]);
  await order("a-unpaid", "alice", "pending", "pending", [["flower-b", 1]]);
  await order("a-cancelled", "alice", "paid", "cancelled", [["flower-b", 1]]);
  await order("a-zero", "alice", "paid", "paid", [["flower-b", 0]]);
  await order("other-customer", "bob", "paid", "paid", [["flower-b", 1]], "alice@example.test");
  await order("future", "alice", "paid", "paid", [["flower-b", 1]], undefined, "2099-01-01T00:00:00Z");
  check("unpaid, cancelled, zero, future and another owner's lines excluded", (await progress("alice")).purchasedProductIds, ["flower-a"]);
  await reject("partial purchases cannot draw", () => call("rpc_kq_claim_producer_purchase_buddie", "alice"), "kq_producer_purchase_incomplete");
  check("ineligible purchase creates no card", await scalar("SELECT count(*)::INTEGER FROM lottery_card_instances"), 0);
  await order("a-second-paid", "alice", "paid", "shipped", [["flower-b::10g", 2]]);
  check("paid purchases accumulate across orders and variants", (await progress("alice")).purchasedProductIds, ["flower-a", "flower-b"]);
  const draws = await Promise.all(Array.from({ length: 6 }, () => call("rpc_kq_claim_producer_purchase_buddie", "alice")));
  check("parallel draw requests award only once", draws.filter((result) => !result.alreadyGranted).length, 1);
  check("parallel draw retries return same instance", new Set(draws.map((result) => result.cardInstanceId)).size, 1);
  check("pool excludes legendary, inactive and other collections", draws[0].cardCode, "HH2026-005");
  check("one Buddie instance has a complete provenance link", await scalar(`SELECT count(*)::INTEGER FROM lottery_card_instances i
    JOIN kq_producer_purchase_buddie_grants g ON g.id=i.producer_purchase_buddie_grant_id AND g.card_instance_id=i.id
    AND i.user_id=g.user_id AND i.card_definition_id=g.card_definition_id`), 1);
  await order("guest-paid", null, "paid", "delivered", [["flower-a", 1], ["flower-b", 1]], " GUEST@EXAMPLE.TEST ");
  check("confirmed guest email qualifies", (await progress("guest")).purchasedProductIds, ["flower-a", "flower-b"]);
  check("unconfirmed guest email does not qualify", (await progress("unverified")).purchasedProductIds, []);
  await reject("unconfirmed guest cannot draw", () => call("rpc_kq_claim_producer_purchase_buddie", "unverified"), "kq_producer_purchase_incomplete");
  await exec("UPDATE lottery_card_definitions SET is_active=false WHERE rarity IN('silver','gold')");
  await reject("empty active pool gives no reward", () => call("rpc_kq_claim_producer_purchase_buddie", "guest"), "kq_producer_buddie_unavailable");
  check("unavailable pool creates no grant", await scalar("SELECT count(*)::INTEGER FROM kq_producer_purchase_buddie_grants"), 1);
  await exec("UPDATE lottery_card_definitions SET is_active=true WHERE code='HH2026-010'");
  check("available silver pool can award silver", (await call("rpc_kq_claim_producer_purchase_buddie", "guest")).cardRarity, "silver");

  await query("INSERT INTO contest_reviews(entry_id,customer_id,status) VALUES('other',$1,'approved')", [ids.overflow]);
  await query("INSERT INTO kq_equipment_wallets(user_id,cash_cents) VALUES($1,2147480000)", [ids.overflow]);
  await reject("integer overflow cannot consume reward", () => call("rpc_kq_claim_producer_completion", "overflow", "producer-two"), "kq_producer_completion_wallet_limit");
  check("overflow rollback preserves wallet", await scalar("SELECT cash_cents FROM kq_equipment_wallets WHERE user_id=$1", [ids.overflow]), 2147480000);
  check("overflow leaves no completion receipt", await scalar("SELECT count(*)::INTEGER FROM kq_producer_completion_grants WHERE user_id=$1", [ids.overflow]), 0);
  const historyAfter = await scalar("SELECT jsonb_build_array((SELECT jsonb_agg(t) FROM kq_notebook_flower_reward_grants t),(SELECT jsonb_agg(t) FROM kq_notebook_flower_reward_packs t),(SELECT jsonb_agg(t) FROM kq_support_booster_entitlements t))");
  check("historical flower packs and entitlements remain unchanged", historyAfter, historyBefore);
  for (const table of ["kq_producer_completion_grants", "kq_producer_purchase_buddie_grants"]) {
    check(`${table} read-only Data API`, await scalar(`SELECT has_table_privilege('service_role',$1,'SELECT')
      AND NOT has_table_privilege('service_role',$1,'INSERT,UPDATE,DELETE')
      AND NOT has_table_privilege('anon',$1,'SELECT,INSERT,UPDATE,DELETE')
      AND NOT has_table_privilege('authenticated',$1,'SELECT,INSERT,UPDATE,DELETE')`, [table]), true);
  }
  check("helpers are unavailable to API roles", await scalar("SELECT NOT has_function_privilege('service_role','kq_producer_notebook_progress(uuid,text)','EXECUTE') AND has_function_privilege('service_role','rpc_kq_get_producer_notebook_progress(uuid)','EXECUTE')"), true);
  const report = { result: "passed", checks: checks.length, details: checks, engine: "PGlite isolated PostgreSQL", concurrency: "Parallel requests submitted; PGlite serializes transactions on its single connection.", fixtures: "Deterministic RNG and reduced opening valuation; actual treasury journal/posting functions.", checkedAt: new Date().toISOString() };
  await mkdir("output/notebook-rewards", { recursive: true });
  await writeFile("output/notebook-rewards/sql-verification.json", JSON.stringify(report, null, 2) + "\n");
  console.log(JSON.stringify(report, null, 2));
} catch (error) {
  console.error(error.message);
  if (error.detail) console.error(error.detail);
  if (error.query) console.error(error.query);
  process.exitCode = 1;
} finally {
  await db.close();
}
