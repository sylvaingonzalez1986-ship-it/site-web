import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

// The reviewed proposal remains the source of truth for labels and provenance.
const csvPath = "docs/bete-de-concours/BUDDIES-PARFUMS-PROPOSITION-2026-10-12.csv";
const lines = readFileSync(resolve(csvPath), "utf8").trim().split(/\r?\n/);
const parseLine = (line) => [...line.matchAll(/"((?:[^"]|"")*)"(?:;|$)/g)].map((match) => match[1].replaceAll('""', '"'));
const headers = parseLine(lines.shift());
const rows = lines.map((line) => Object.fromEntries(parseLine(line).map((value, index) => [headers[index], value])));
const slug = (label) => label.normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase().replace(/[^a-z0-9]+/g, "-");
const labels = [...new Set(rows.flatMap((row) => [row.note_dominante, row.note_secondaire]))].sort((a, b) => a.localeCompare(b, "fr"));
if (rows.length !== 52 || new Set(rows.map((row) => row.code)).size !== 52 || labels.some((label) => !label)) {
  throw new Error("Expected 52 unique Buddies with exactly two named flavors.");
}

const flavors = labels.map((label) => `  ${JSON.stringify(slug(label))}: { code: ${JSON.stringify(slug(label))}, label: ${JSON.stringify(label)}, image: "/placard/flavors-v1/${slug(label)}.webp" },`).join("\n");
const profiles = rows.map((row) => {
  const profile = {
    flavors: [slug(row.note_dominante), slug(row.note_secondaire)],
    status: row.statut,
    sources: [row.source_principale, row.source_complementaire].filter(Boolean),
  };
  return `  ${JSON.stringify(row.code)}: ${JSON.stringify(profile)},`;
}).join("\n");

writeFileSync(resolve("src/lib/kanab-quest-buddie-flavors.ts"), `// Generated by scripts/sync-buddie-flavors.mjs from ${csvPath}.
// These are game profiles for the cited selections, not universal botanical claims.
// Scope, caveats and the complete source descriptions are preserved in that CSV.
// Keep this module independent of kanab-quest-game to avoid a client/server import cycle.

export type KqFlavor = Readonly<{ code: string; label: string; image: string }>;

export const KQ_FLAVORS = {
${flavors}
} as const satisfies Record<string, KqFlavor>;

export type KqFlavorCode = keyof typeof KQ_FLAVORS;
export type KqBuddieFlavorProfile = Readonly<{
  flavors: readonly [KqFlavorCode, KqFlavorCode];
  status: string;
  sources: readonly string[];
}>;

export const KQ_BUDDIE_FLAVOR_PROFILES = {
${profiles}
} as const satisfies Record<string, KqBuddieFlavorProfile>;

const profilesByCode: Readonly<Record<string, KqBuddieFlavorProfile | undefined>> = KQ_BUDDIE_FLAVOR_PROFILES;
const noFlavors: readonly [] = [];

export function getKqBuddieFlavors(code: string): readonly [KqFlavor, KqFlavor] | readonly [] {
  const profile = Object.hasOwn(profilesByCode, code) ? profilesByCode[code] : undefined;
  return profile ? [KQ_FLAVORS[profile.flavors[0]], KQ_FLAVORS[profile.flavors[1]]] : noFlavors;
}
`);
console.log(`Synced ${rows.length} Buddies and ${labels.length} flavor illustrations.`);
