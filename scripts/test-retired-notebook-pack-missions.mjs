// Isolated PostgreSQL verification: node scripts/test-retired-notebook-pack-missions.mjs <pglite-dist/index.js>
import assert from "node:assert/strict";
import { readFile, mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";

const { PGlite } = await import(process.argv[2] ? pathToFileURL(path.resolve(process.argv[2])).href : "@electric-sql/pglite");
const db = new PGlite();
const users = {
  history: "00000000-0000-4000-8000-000000000001",
  legacy: "00000000-0000-4000-8000-000000000002",
  fresh: "00000000-0000-4000-8000-000000000003",
};
const checks = [];
const read = (file) => readFile(path.resolve(file), "utf8");
const query = (sql, args = []) => db.query(sql, args);
const scalar = async (sql, args = []) => Object.values((await query(sql, args)).rows[0])[0];
const check = (name, actual, expected) => { assert.deepEqual(actual, expected, name); checks.push(name); };
const reject = async (name, operation, message) => {
  await assert.rejects(operation, (error) => error.message === message, name);
  checks.push(name);
};
const notebook = (user, badge) => scalar("SELECT public.rpc_kq_grant_notebook_badge_reward($1,$2)", [users[user], badge]);
const legacy = (user, badge) => scalar("SELECT public.rpc_claim_contest_badge_reward($1,$2)", [users[user], badge]);
const mission = (user) => scalar("SELECT public.rpc_kq_claim_mission($1,'first-harvest')", [users[user]]);
const rowsExceptRules = async () => {
  const tables = (await query("SELECT tablename FROM pg_tables WHERE schemaname='public' AND tablename<>'kq_notebook_reward_rules' ORDER BY tablename")).rows;
  const result = {};
  for (const { tablename } of tables) {
    assert.match(tablename, /^[a-z_]+$/);
    result[tablename] = (await query(`SELECT to_jsonb(row) AS row FROM public."${tablename}" row ORDER BY to_jsonb(row)::text`)).rows;
  }
  return result;
};

try {
  await db.exec(`
    CREATE SCHEMA auth; CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role;
    CREATE TABLE auth.users(id UUID PRIMARY KEY);
    CREATE TABLE contest_badges(id TEXT PRIMARY KEY, code TEXT NOT NULL UNIQUE, label TEXT NOT NULL);
    CREATE TABLE contest_profile_badges(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      customer_id UUID NOT NULL REFERENCES auth.users, badge_id TEXT NOT NULL REFERENCES contest_badges,
      awarded_at TIMESTAMPTZ NOT NULL DEFAULT now(), UNIQUE(customer_id,badge_id));
    CREATE TABLE lottery_card_collections(id UUID PRIMARY KEY DEFAULT gen_random_uuid(), code TEXT UNIQUE, is_active BOOLEAN);
    CREATE TABLE lottery_tickets(id UUID PRIMARY KEY DEFAULT gen_random_uuid(), user_id UUID REFERENCES auth.users,
      note TEXT, created_by TEXT, created_at TIMESTAMPTZ DEFAULT now());
    CREATE TABLE kq_support_booster_entitlements(id UUID PRIMARY KEY DEFAULT gen_random_uuid(), user_id UUID REFERENCES auth.users,
      ticket_id UUID REFERENCES lottery_tickets, source TEXT NOT NULL DEFAULT 'ticket', reward_key TEXT UNIQUE,
      status TEXT NOT NULL DEFAULT 'available' CHECK(status IN ('available','opened')),
      card_count INTEGER NOT NULL DEFAULT 3, created_at TIMESTAMPTZ NOT NULL DEFAULT now(), opened_at TIMESTAMPTZ,
      CONSTRAINT fixture_opened_consistency CHECK((status='opened')=(opened_at IS NOT NULL)),
      CONSTRAINT kq_support_booster_entitlements_source_check CHECK(source IN ('ticket','arena_streak')),
      CONSTRAINT kq_support_booster_entitlements_check CHECK(
        (source='ticket' AND ticket_id IS NOT NULL AND reward_key IS NULL)
        OR (source='arena_streak' AND ticket_id IS NULL AND reward_key IS NOT NULL)));
    CREATE TABLE lottery_card_instances(id UUID PRIMARY KEY DEFAULT gen_random_uuid(), user_id UUID REFERENCES auth.users,
      kq_support_entitlement_id UUID REFERENCES kq_support_booster_entitlements, card_code TEXT NOT NULL);
    CREATE TABLE kq_runs(id UUID PRIMARY KEY DEFAULT gen_random_uuid(), user_id UUID REFERENCES auth.users, status TEXT);
    CREATE TABLE kq_flowers(id UUID PRIMARY KEY DEFAULT gen_random_uuid(), owner_id UUID REFERENCES auth.users,
      run_id UUID REFERENCES kq_runs, variety_code TEXT, quality INTEGER);
    CREATE TABLE kq_commerce_accounts(user_id UUID PRIMARY KEY REFERENCES auth.users, clients INTEGER DEFAULT 0, shop_partners INTEGER DEFAULT 0);
    CREATE TABLE kq_producer_completion_grants(user_id UUID REFERENCES auth.users, producer_id TEXT, producer_name TEXT,
      cash_cents INTEGER, qualifying_product_ids TEXT[], season_id TEXT, created_at TIMESTAMPTZ DEFAULT now(),
      PRIMARY KEY(user_id,producer_id));
    CREATE TABLE kq_equipment_wallets(user_id UUID PRIMARY KEY REFERENCES auth.users,cash_cents INTEGER);
    CREATE TABLE contest_tester_points(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, customer_id UUID REFERENCES auth.users,
      points INTEGER NOT NULL, reason TEXT NOT NULL);
    -- Ticket issuance is a deterministic fixture; both badge claim bodies are the actual migrations.
    CREATE FUNCTION rpc_admin_grant_lottery_tickets(p_user UUID,p_count INTEGER,p_note TEXT,p_admin TEXT)
      RETURNS VOID LANGUAGE sql AS $$
        INSERT INTO lottery_tickets(user_id,note,created_by)
        SELECT p_user,p_note,p_admin FROM generate_series(1,p_count)
      $$;
  `);
  for (const id of Object.values(users)) await query("INSERT INTO auth.users VALUES($1)", [id]);
  await db.exec(await read("supabase/migrations/20260426000300_contest_badge_reward_claims.sql"));
  const tokens = await read("supabase/migrations/20260725000900_kq_culture_token_wallet.sql");
  await db.exec(tokens.split("ALTER TABLE public.kq_runs")[0] + "COMMIT;");
  await db.exec(await read("supabase/migrations/20260725001000_kq_dormant_notebook_rewards.sql"));
  await db.exec(await read("supabase/migrations/20260725002200_kq_serialize_notebook_reward_grants.sql"));
  await db.exec(await read("supabase/migrations/20260727000100_kq_notebook_rewards_70_30.sql"));
  const activation = await read("supabase/migrations/20260804000100_kq_two_notebook_missions_and_producer_purchase_heritage.sql");
  await db.exec(activation.split("-- A producer Heritage")[0] + "COMMIT;");
  await db.exec(await read("supabase/migrations/20260913000500_kq_mission_center.sql"));
  await db.exec(`
    GRANT SELECT ON kq_notebook_reward_rules,kq_notebook_reward_grants TO service_role;
    INSERT INTO contest_badges VALUES
      ('first','premier-carnet','Premier Carnet'),('combo','combo-aromatique','Combo Aromatique'),
      ('nose','nez-absolu','Nez Absolu'),('level','testeur','Testeur');
    INSERT INTO lottery_card_collections(code,is_active) VALUES('BOTTE_DU_CHANVRIER_2026',true);
    -- A separately enabled rule must not be modified by the retirement.
    UPDATE kq_notebook_reward_rules SET is_active=true WHERE badge_code='nez-absolu';
  `);
  for (const [name, userId] of Object.entries(users)) {
    await query("INSERT INTO contest_profile_badges(customer_id,badge_id,reward_pack_count) VALUES($1,'first',$2),($1,'combo',$3)",
      [userId, name === "history" ? 0 : 1, name === "history" ? 0 : 3]);
    await query("INSERT INTO kq_commerce_accounts(user_id) VALUES($1)", [userId]);
    const run = await scalar("INSERT INTO kq_runs(user_id,status) VALUES($1,'completed') RETURNING id", [userId]);
    await query("INSERT INTO kq_flowers(owner_id,run_id,variety_code,quality) VALUES($1,$2,'HH2026-005',10)", [userId, run]);
  }
  await query("INSERT INTO contest_profile_badges(customer_id,badge_id,reward_pack_count) VALUES($1,'nose',0),($1,'level',1)", [users.fresh]);
  const badgeId = (user, code) => scalar("SELECT id FROM contest_profile_badges WHERE customer_id=$1 AND badge_id=$2", [users[user], code]);
  for (const code of ["first", "combo"]) {
    check(`current notebook claim originally awards ${code}`, (await notebook("history", await badgeId("history", code))).alreadyGranted, false);
  }
  check("legacy first-notebook path originally creates a ticket", await legacy("legacy", "first"), 1);
  check("legacy aromatic-combo path originally creates three tickets", await legacy("legacy", "combo"), 3);
  check("Placard mission originally grants its own pack", (await mission("history")).cardCount, 3);
  const opened = await scalar("UPDATE kq_support_booster_entitlements SET status='opened',opened_at=now() WHERE reward_key=$1 RETURNING id",
    [`notebook-badge:${await badgeId("history", "combo")}:booster:1`]);
  await query("INSERT INTO lottery_card_instances(user_id,kq_support_entitlement_id,card_code) VALUES($1,$2,'BOTTE-001')", [users.history, opened]);
  await query("INSERT INTO kq_culture_token_wallets(user_id,balance) VALUES($1,2)", [users.history]);
  await query("INSERT INTO kq_culture_token_ledger(user_id,amount,reason,reward_key) VALUES($1,2,'notebook_badge','old-notebook-tokens')", [users.history]);
  await query("INSERT INTO kq_producer_completion_grants(user_id,producer_id,producer_name,cash_cents,qualifying_product_ids,season_id) VALUES($1,'producer','Ferme',20000,ARRAY['flower-a','flower-b'],'season')", [users.history]);
  await query("INSERT INTO kq_equipment_wallets VALUES($1,55000)", [users.history]);
  await query("INSERT INTO contest_tester_points(customer_id,points,reason) VALUES($1,120,'review')", [users.history]);

  const protectedBefore = await rowsExceptRules();
  const otherRulesBefore = (await query("SELECT * FROM kq_notebook_reward_rules WHERE badge_code NOT IN ('premier-carnet','combo-aromatique') ORDER BY badge_code")).rows;
  const functionsBefore = (await query("SELECT proname,pg_get_functiondef(oid) FROM pg_proc WHERE pronamespace='public'::regnamespace AND proname<>'rpc_claim_contest_badge_reward' ORDER BY proname")).rows;
  const migration = await read("supabase/migrations/20260927000300_retire_notebook_pack_missions.sql");
  await db.exec(migration);
  check("only the two retired notebook rules are inactive", (await query("SELECT badge_code,is_active,support_boosters,culture_tokens FROM kq_notebook_reward_rules WHERE badge_code IN ('premier-carnet','combo-aromatique') ORDER BY badge_code")).rows, [
    { badge_code: "combo-aromatique", is_active: false, support_boosters: 1, culture_tokens: 0 },
    { badge_code: "premier-carnet", is_active: false, support_boosters: 1, culture_tokens: 0 },
  ]);
  check("all other rules retain their amounts, activation and timestamps", (await query("SELECT * FROM kq_notebook_reward_rules WHERE badge_code NOT IN ('premier-carnet','combo-aromatique') ORDER BY badge_code")).rows, otherRulesBefore);
  check("migration preserves every badge, grant, pack, ticket, card, token, producer credit and point", await rowsExceptRules(), protectedBefore);
  check("only the legacy badge claim function is replaced", (await query("SELECT proname,pg_get_functiondef(oid) FROM pg_proc WHERE pronamespace='public'::regnamespace AND proname<>'rpc_claim_contest_badge_reward' ORDER BY proname")).rows, functionsBefore);
  const retiredRules = (await query("SELECT * FROM kq_notebook_reward_rules ORDER BY badge_code")).rows;
  await db.exec(migration);
  check("retirement rerun leaves timestamps and amounts unchanged", (await query("SELECT * FROM kq_notebook_reward_rules ORDER BY badge_code")).rows, retiredRules);
  check("retirement rerun creates or removes no reward", await rowsExceptRules(), protectedBefore);

  for (const code of ["first", "combo"]) {
    const freshBadge = await badgeId("fresh", code);
    const historicalBadge = await badgeId("history", code);
    await reject(`new notebook claim blocked for ${code}`, () => notebook("fresh", freshBadge), "kq_notebook_rewards_inactive");
    await reject(`old positive legacy counter cannot grant ${code}`, () => legacy("fresh", code), "reward_not_claimable");
    await reject(`retired notebook receipt cannot mint again for ${code}`, () => notebook("history", historicalBadge), "kq_notebook_rewards_inactive");
    await reject(`historical legacy claim keeps its replay error for ${code}`, () => legacy("legacy", code), "reward_already_claimed");
  }
  const retiredBadge = await badgeId("fresh", "first");
  const retries = await Promise.allSettled(Array.from({ length: 6 }, () => notebook("fresh", retiredBadge)));
  check("repeated notebook requests all reject without grants", retries.every(result => result.status === "rejected" && result.reason.message === "kq_notebook_rewards_inactive"), true);
  check("all rejected paths leave every existing reward untouched", await rowsExceptRules(), protectedBefore);
  check("historical available and opened notebook packs remain in stock", (await query("SELECT status,count(*)::INTEGER AS count FROM kq_support_booster_entitlements WHERE user_id=$1 AND source='notebook_badge' GROUP BY status ORDER BY status", [users.history])).rows, [
    { status: "available", count: 1 }, { status: "opened", count: 1 },
  ]);
  check("retirement preserves old positive counters rather than rewriting badges", (await query("SELECT reward_pack_count FROM contest_profile_badges WHERE customer_id=$1 AND badge_id IN ('first','combo') ORDER BY badge_id", [users.fresh])).rows, [
    { reward_pack_count: 3 }, { reward_pack_count: 1 },
  ]);
  const otherNotebook = await notebook("fresh", await badgeId("fresh", "nose"));
  check("a separately active notebook rule still grants its original reward", [otherNotebook.grant.support_boosters, otherNotebook.cultureTokenBalance, otherNotebook.alreadyGranted], [2, 1, false]);
  check("unrelated legacy level reward is still claimable", await legacy("fresh", "level"), 1);
  await reject("unrelated legacy claim remains idempotent", () => legacy("fresh", "level"), "reward_already_claimed");
  const freshMission = await mission("fresh");
  check("Placard first-harvest mission still awards its pack", [freshMission.cardCount, freshMission.replayed], [3, false]);
  check("Placard mission retry returns its original pack", (await mission("fresh")).entitlementId, freshMission.entitlementId);
  check("historical Placard mission remains already claimed", (await mission("history")).replayed, true);
  check("producer bonus receipt and wallet remain unchanged", [
    await scalar("SELECT cash_cents FROM kq_producer_completion_grants WHERE user_id=$1", [users.history]),
    await scalar("SELECT cash_cents FROM kq_equipment_wallets WHERE user_id=$1", [users.history]),
  ], [20000, 55000]);
  check("tasting points and historical cards remain unchanged", [
    await scalar("SELECT sum(points)::INTEGER FROM contest_tester_points WHERE customer_id=$1", [users.history]),
    await scalar("SELECT count(*)::INTEGER FROM lottery_card_instances WHERE user_id=$1", [users.history]),
  ], [120, 1]);
  for (const rpc of ["rpc_claim_contest_badge_reward(uuid,text)", "rpc_kq_grant_notebook_badge_reward(uuid,bigint)"]) {
    check(`${rpc} stays service-role only`, await scalar(`SELECT has_function_privilege('service_role',$1,'EXECUTE')
      AND NOT has_function_privilege('anon',$1,'EXECUTE')
      AND NOT has_function_privilege('authenticated',$1,'EXECUTE')`, [rpc]), true);
  }
  check("unlocked grant remains inaccessible to Data API roles", await scalar(`SELECT
    NOT has_function_privilege('service_role','rpc_kq_grant_notebook_badge_reward_unlocked(uuid,bigint)','EXECUTE')
    AND NOT has_function_privilege('anon','rpc_kq_grant_notebook_badge_reward_unlocked(uuid,bigint)','EXECUTE')
    AND NOT has_function_privilege('authenticated','rpc_kq_grant_notebook_badge_reward_unlocked(uuid,bigint)','EXECUTE')`), true);
  check("new legacy guard preserves SECURITY DEFINER and fixed search path", await scalar(
    "SELECT prosecdef AND 'search_path=public'=ANY(proconfig) FROM pg_proc WHERE oid='rpc_claim_contest_badge_reward(uuid,text)'::regprocedure"), true);
  const report = {
    result: "passed", checks: checks.length, details: checks, engine: "PGlite isolated PostgreSQL",
    fixtures: "Actual notebook, legacy badge and Placard mission RPCs; deterministic lottery-ticket issuance; producer receipts and points retained as data sentinels.",
    concurrency: "Parallel retries submitted; PGlite serializes statements on its single connection.",
    checkedAt: new Date().toISOString(),
  };
  await mkdir("output/retired-notebook-missions", { recursive: true });
  await writeFile("output/retired-notebook-missions/sql-verification.json", JSON.stringify(report, null, 2) + "\n");
  console.log(JSON.stringify(report, null, 2));
} catch (error) {
  console.error(error.message);
  if (error.detail) console.error(error.detail);
  process.exitCode = 1;
} finally {
  await db.close();
}
