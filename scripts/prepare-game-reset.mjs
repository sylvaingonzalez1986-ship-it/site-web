// Generate the reviewed, one-off reset. This script never connects to Supabase.
import { readFile, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const scope = JSON.parse(await readFile('scripts/lib/game-reset-20261115-scope.json', 'utf8'));
const all = [...scope.resetTables, ...scope.mixedTables, ...scope.preserveTables].sort();
assert.equal(new Set(all).size, all.length);
assert(all.every(name => /^[a-z_0-9]+$/.test(name)));
assert.deepEqual([...scope.deleteOrder].sort(), [...scope.resetTables].sort());
const array = names => `ARRAY[${names.map(name => `'${name}'`).join(',')}]::text[]`;
const sql = `-- One-off reset requested on 2026-11-15. Generated by prepare-game-reset.mjs.
-- DEFAULT: rehearse and ROLLBACK. Applying requires the separate reviewed runner.
-- No migration push, TRUNCATE CASCADE, auth deletion or season change.
BEGIN ISOLATION LEVEL REPEATABLE READ;
SET LOCAL lock_timeout='5s';
SET LOCAL statement_timeout='120s';
-- Acquire every affected-table lock BEFORE the first snapshot. This drains old
-- game writers without blocking writes to protected shop/Carnet tables. The
-- repeatable snapshot sees our own changes (including cascades) for invariant
-- checks while allowing unrelated purchases/reviews to proceed concurrently.
LOCK TABLE ${[...scope.resetTables, ...scope.mixedTables].sort().map(name=>`public.${name}`).join(',')} IN ACCESS EXCLUSIVE MODE;
SELECT pg_advisory_xact_lock(hashtextextended('game-reset-20261115',0));

DO $preflight$
DECLARE names text[]; name text;
BEGIN
 IF to_regnamespace('game_reset_20261115') IS NOT NULL THEN
   RAISE EXCEPTION 'game_reset_already_applied';
 END IF;
 SELECT array_agg(c.relname::text ORDER BY c.relname) INTO names
 FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
 WHERE n.nspname='public' AND c.relkind='r';
 IF names IS DISTINCT FROM ${array(all)} THEN RAISE EXCEPTION 'game_reset_schema_changed'; END IF;
 IF EXISTS(SELECT 1 FROM public.kq_support_booster_entitlements WHERE source NOT IN
   ('ticket','arena_streak','notebook_badge','season_reward','points_purchase','welcome_pack',
    'pvp_win','notebook_flower','mission','achievement','pioneer_pack','contest_bundle','arena_feedback'))
 THEN RAISE EXCEPTION 'game_reset_unknown_booster_source'; END IF;
 -- The inspected database contains only Carnet heritages and no fragment ledger.
 -- Stop rather than silently discard new crafted/purchased heritage activity.
 IF EXISTS(SELECT 1 FROM public.kq_heritage_draws WHERE source<>'producer_notebook')
   OR EXISTS(SELECT 1 FROM public.kq_heritage_fragment_ledger)
 THEN RAISE EXCEPTION 'game_reset_heritage_inventory_changed'; END IF;
 IF EXISTS(SELECT 1 FROM public.kq_pioneer_pack_grants WHERE cash_cents<>500000 OR pack_count<>10)
 THEN RAISE EXCEPTION 'game_reset_pioneer_terms_changed'; END IF;
END $preflight$;

-- Private, transactionally consistent archive; no API role can access it.
CREATE SCHEMA game_reset_20261115 AUTHORIZATION postgres;
REVOKE ALL ON SCHEMA game_reset_20261115 FROM PUBLIC,anon,authenticated,service_role;
CREATE TABLE game_reset_20261115.rows(table_name text NOT NULL, row_data jsonb NOT NULL);
CREATE INDEX reset_rows_table ON game_reset_20261115.rows(table_name);
CREATE TABLE game_reset_20261115.meta(id boolean PRIMARY KEY CHECK(id), report jsonb NOT NULL);
CREATE TABLE game_reset_20261115.retired_requests(
 table_name text NOT NULL,user_id text NOT NULL,request_key text NOT NULL,
 PRIMARY KEY(table_name,user_id,request_key)
);
ALTER TABLE game_reset_20261115.rows ENABLE ROW LEVEL SECURITY;
ALTER TABLE game_reset_20261115.meta ENABLE ROW LEVEL SECURITY;
ALTER TABLE game_reset_20261115.retired_requests ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE game_reset_20261115.rows,game_reset_20261115.meta,
 game_reset_20261115.retired_requests FROM PUBLIC,anon,authenticated,service_role;

CREATE TEMP TABLE reset_protected(table_name text PRIMARY KEY,fingerprint text) ON COMMIT DROP;
CREATE TEMP TABLE reset_triggers ON COMMIT DROP AS
 SELECT tgrelid::regclass::text AS table_name,tgname,tgenabled
 FROM pg_trigger WHERE NOT tgisinternal
 AND tgrelid IN (SELECT ('public.'||unnest(${array(scope.resetTables)}))::regclass);
DO $backup$
DECLARE name text; digest text; item record;
BEGIN
 FOREACH name IN ARRAY ${array([...scope.resetTables, ...scope.mixedTables])} LOOP
   EXECUTE format('INSERT INTO game_reset_20261115.rows SELECT %L,to_jsonb(t) FROM public.%I t',name,name);
 END LOOP;
 FOREACH name IN ARRAY ${array(scope.preserveTables)} LOOP
   EXECUTE format('SELECT md5(COALESCE(string_agg(md5(to_jsonb(t)::text),'''' ORDER BY md5(to_jsonb(t)::text)),'''')) FROM public.%I t',name) INTO digest;
   INSERT INTO reset_protected VALUES(name,digest);
 END LOOP;
 FOREACH name IN ARRAY ${array(scope.staleRequestTables)} LOOP
   INSERT INTO game_reset_20261115.retired_requests
   SELECT name,COALESCE(row_data->>'user_id',row_data->>'owner_id'),row_data->>'request_key' FROM game_reset_20261115.rows
   WHERE table_name=name AND row_data->>'request_key' IS NOT NULL
   ON CONFLICT DO NOTHING;
 END LOOP;
 -- Only user triggers on explicitly reviewed reset tables; FKs stay enforced.
 -- This prevents immutable logs/treasury observers from rebuilding old activity.
 FOR item IN SELECT * FROM reset_triggers WHERE tgenabled<>'D' LOOP
   EXECUTE format('ALTER TABLE %s DISABLE TRIGGER %I',item.table_name,item.tgname);
 END LOOP;
END $backup$;

CREATE TEMP TABLE reset_wallet_owners ON COMMIT DROP AS
 SELECT user_id FROM public.kq_equipment_wallets UNION SELECT user_id FROM public.kq_pioneer_pack_grants;
CREATE TEMP TABLE reset_welcome_owners ON COMMIT DROP AS
 SELECT user_id FROM public.lottery_welcome_pack_claims UNION SELECT user_id FROM reset_wallet_owners;
-- Historical welcome packs did not have ticket_id. Their exact transaction timestamp
-- and explicit system reason identify them; generic admin gifts are preserved.
CREATE TEMP TABLE reset_welcome_tickets ON COMMIT DROP AS
 SELECT t.id FROM public.lottery_tickets t WHERE t.order_id IS NULL AND (
 EXISTS(SELECT 1 FROM public.lottery_welcome_pack_claims w WHERE w.ticket_id=t.id)
 OR EXISTS(SELECT 1 FROM public.lottery_audit_log a WHERE a.user_id=t.user_id
   AND a.created_at=t.created_at AND a.event_type='admin_grant'
   AND a.details->>'reason'='Pack de bienvenue — inscription'));
CREATE TEMP TABLE reset_boosters ON COMMIT DROP AS
 SELECT id FROM public.kq_support_booster_entitlements WHERE source IN
 ('arena_streak','season_reward','pvp_win','mission','achievement','welcome_pack');
CREATE TEMP TABLE reset_cards ON COMMIT DROP AS
 SELECT i.id FROM public.lottery_card_instances i WHERE
 i.source_bot_battle_id IS NOT NULL OR i.game_mission_reward_id IS NOT NULL
 OR i.starter_buddie_recovery_id IS NOT NULL
 OR i.kq_support_entitlement_id IN (SELECT id FROM reset_boosters)
 OR i.ticket_id IN (SELECT id FROM reset_welcome_tickets);
DO $origins$
BEGIN
 IF EXISTS(SELECT 1 FROM public.lottery_card_instances i
 LEFT JOIN public.lottery_tickets t ON t.id=i.ticket_id
 LEFT JOIN public.kq_support_booster_entitlements e ON e.id=i.kq_support_entitlement_id
 WHERE i.id IN (SELECT id FROM reset_cards) AND
 (t.order_id IS NOT NULL OR i.pioneer_grant_id IS NOT NULL
 OR i.producer_purchase_buddie_grant_id IS NOT NULL OR i.community_mission_reward_id IS NOT NULL
 OR i.contest_bundle_order_id IS NOT NULL OR e.source IN
 ('points_purchase','notebook_badge','notebook_flower','contest_bundle','arena_feedback','pioneer_pack')))
 THEN RAISE EXCEPTION 'game_reset_conflicting_card_origins'; END IF;
END $origins$;

-- Drop reservations before cards. Other child/parent ordering is catalog-verified.
DELETE FROM public.kq_zone_card_reservations;
DELETE FROM public.lottery_card_instances WHERE id IN (SELECT id FROM reset_cards);
DELETE FROM public.kq_support_booster_entitlements WHERE id IN (SELECT id FROM reset_boosters);
-- Do not delete old tickets: discounts/rewards already attached remain valid.
UPDATE public.lottery_tickets SET status='scratched',scratched_at=now()
 WHERE id IN (SELECT id FROM reset_welcome_tickets) AND status='available';
DELETE FROM public.lottery_welcome_pack_claims;
DO $clear$
DECLARE name text;
BEGIN
 FOREACH name IN ARRAY ${array(scope.deleteOrder)} LOOP
   EXECUTE format('DELETE FROM public.%I',name);
 END LOOP;
END $clear$;
SET CONSTRAINTS ALL IMMEDIATE;

-- Base budget comes from the current server default. Preserve Pioneer receipts,
-- original Buddie, souvenir and pack inventory; never reroll or duplicate gifts.
INSERT INTO public.kq_equipment_wallets(user_id) SELECT user_id FROM reset_wallet_owners;
UPDATE public.kq_equipment_wallets w SET cash_cents=w.cash_cents+g.cash_cents
 FROM public.kq_pioneer_pack_grants g WHERE g.user_id=w.user_id;
INSERT INTO public.kq_school_tournament_championship(singleton) VALUES(true);
DO $restore$
DECLARE item record;
BEGIN
 FOR item IN SELECT * FROM reset_triggers WHERE tgenabled<>'D' LOOP
   EXECUTE format('ALTER TABLE %s ENABLE %s TRIGGER %I',item.table_name,
     CASE item.tgenabled WHEN 'A' THEN 'ALWAYS' WHEN 'R' THEN 'REPLICA' ELSE '' END,item.tgname);
 END LOOP;
 FOR item IN SELECT user_id FROM reset_welcome_owners LOOP
   PERFORM public.rpc_claim_welcome_pack(item.user_id);
 END LOOP;
END $restore$;

-- Old browser recovery commands must fail atomically instead of debiting a fresh wallet.
CREATE FUNCTION game_reset_20261115.reject_retired_request() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog AS $guard$
BEGIN
 IF EXISTS(SELECT 1 FROM game_reset_20261115.retired_requests r
   WHERE r.table_name=TG_TABLE_NAME AND r.user_id=COALESCE(to_jsonb(NEW)->>'user_id',to_jsonb(NEW)->>'owner_id')
   AND r.request_key=to_jsonb(NEW)->>'request_key') THEN
   RAISE EXCEPTION 'game_reset_command_expired';
 END IF;
 RETURN NEW;
END $guard$;
REVOKE ALL ON FUNCTION game_reset_20261115.reject_retired_request() FROM PUBLIC,anon,authenticated,service_role;
DO $guards$
DECLARE name text;
BEGIN
 FOREACH name IN ARRAY ${array(scope.staleRequestTables)} LOOP
   EXECUTE format('CREATE TRIGGER game_reset_reject_old_command BEFORE INSERT ON public.%I FOR EACH ROW EXECUTE FUNCTION game_reset_20261115.reject_retired_request()',name);
 END LOOP;
END $guards$;

DO $verify$
DECLARE item record; digest text; amount bigint; total bigint;
BEGIN
 FOR item IN SELECT * FROM reset_protected LOOP
   EXECUTE format('SELECT md5(COALESCE(string_agg(md5(to_jsonb(t)::text),'''' ORDER BY md5(to_jsonb(t)::text)),'''')) FROM public.%I t',item.table_name) INTO digest;
   IF digest IS DISTINCT FROM item.fingerprint THEN RAISE EXCEPTION 'game_reset_protected_table_changed: %',item.table_name; END IF;
 END LOOP;
 IF EXISTS(SELECT row_data FROM game_reset_20261115.rows WHERE table_name='lottery_card_instances'
     AND (row_data->>'id')::uuid NOT IN (SELECT id FROM reset_cards)
     EXCEPT SELECT to_jsonb(i) FROM public.lottery_card_instances i)
 OR EXISTS(SELECT to_jsonb(i) FROM public.lottery_card_instances i
     EXCEPT SELECT row_data FROM game_reset_20261115.rows WHERE table_name='lottery_card_instances')
 THEN RAISE EXCEPTION 'game_reset_protected_cards_changed'; END IF;
 IF EXISTS(SELECT row_data FROM game_reset_20261115.rows WHERE table_name='kq_support_booster_entitlements'
     AND (row_data->>'id')::uuid NOT IN (SELECT id FROM reset_boosters)
     EXCEPT SELECT to_jsonb(e) FROM public.kq_support_booster_entitlements e)
 THEN RAISE EXCEPTION 'game_reset_protected_boosters_changed'; END IF;
 IF EXISTS(SELECT row_data FROM game_reset_20261115.rows WHERE table_name='lottery_tickets'
     AND (row_data->>'id')::uuid NOT IN (SELECT id FROM reset_welcome_tickets)
     EXCEPT SELECT to_jsonb(t) FROM public.lottery_tickets t)
 THEN RAISE EXCEPTION 'game_reset_protected_tickets_changed'; END IF;
 IF EXISTS(SELECT row_data FROM game_reset_20261115.rows WHERE table_name='lottery_audit_log'
     EXCEPT SELECT to_jsonb(a) FROM public.lottery_audit_log a)
 THEN RAISE EXCEPTION 'game_reset_audit_history_changed'; END IF;
 IF EXISTS(SELECT 1 FROM public.kq_equipment_wallets w LEFT JOIN public.kq_pioneer_pack_grants g USING(user_id)
   WHERE w.cash_cents<>100000+COALESCE(g.cash_cents,0) OR w.reputation<>0)
 THEN RAISE EXCEPTION 'game_reset_incorrect_starting_budget'; END IF;
 IF (SELECT count(*) FROM public.kq_equipment_wallets)<>(SELECT count(*) FROM reset_wallet_owners)
 THEN RAISE EXCEPTION 'game_reset_missing_wallet'; END IF;
 FOREACH item.table_name IN ARRAY ${array(scope.resetTables.filter(n=>!['kq_equipment_wallets','kq_school_tournament_championship'].includes(n)))} LOOP
   EXECUTE format('SELECT count(*) FROM public.%I',item.table_name) INTO amount;
   IF amount<>0 THEN RAISE EXCEPTION 'game_reset_remaining_progress: %',item.table_name; END IF;
 END LOOP;
 IF (SELECT count(*) FROM public.lottery_welcome_pack_claims)<>(SELECT count(*) FROM reset_welcome_owners)
 THEN RAISE EXCEPTION 'game_reset_missing_welcome'; END IF;
 IF EXISTS(SELECT 1 FROM public.lottery_welcome_pack_claims w JOIN public.lottery_tickets t ON t.id=w.ticket_id
   WHERE t.status<>'available' OR w.opening_result IS NOT NULL)
 THEN RAISE EXCEPTION 'game_reset_invalid_welcome'; END IF;
 IF EXISTS(SELECT 1 FROM reset_triggers old JOIN pg_trigger t ON t.tgname=old.tgname
    AND t.tgrelid=old.table_name::regclass WHERE t.tgenabled<>old.tgenabled)
 THEN RAISE EXCEPTION 'game_reset_trigger_state_changed'; END IF;
 INSERT INTO game_reset_20261115.meta VALUES(true,jsonb_build_object(
   'resetAt',now(),'wallets',(SELECT count(*) FROM reset_wallet_owners),
   'pioneers',(SELECT count(*) FROM public.kq_pioneer_pack_grants),
   'removedGameCards',(SELECT count(*) FROM reset_cards),'removedGameBoosters',(SELECT count(*) FROM reset_boosters),
   'freshWelcomePacks',(SELECT count(*) FROM reset_welcome_owners),
   'preservedReviews',(SELECT count(*) FROM public.contest_reviews),
   'preservedNotebookPointRows',(SELECT count(*) FROM public.contest_tester_points),
   'preservedCards',(SELECT count(*) FROM public.lottery_card_instances),
   'protectedTableFingerprints',(SELECT jsonb_object_agg(table_name,fingerprint) FROM reset_protected),
   'archivedRows',(SELECT count(*) FROM game_reset_20261115.rows),
   'retiredRequests',(SELECT count(*) FROM game_reset_20261115.retired_requests)));
END $verify$;
SELECT report FROM game_reset_20261115.meta;
ROLLBACK;
`;
await writeFile('scripts/sql/reset-game-progress-2026-11-15.sql', sql);
console.log(`Prepared rollback-only SQL: ${scope.resetTables.length} reset tables, ${scope.preserveTables.length} protected tables.`);
