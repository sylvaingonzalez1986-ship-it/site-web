// Pure, reproducible migration generation. Does not connect to a database.
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { createServer } from "vite";

const vite = await createServer({ configFile: false, envDir: false, resolve: { alias: { "@": path.resolve("src") } }, server: { middlewareMode: true, watch: null } });
try {
  const { KQ_CARDS, getKqCardTradeoff } = await vite.ssrLoadModule("/src/lib/kanab-quest-game.ts");
  const { getKqCardArtwork } = await vite.ssrLoadModule("/src/lib/kanab-quest-artwork.ts");
  const previous = await readFile("supabase/migrations/20260912000300_kq_distinct_talents.sql", "utf8");
  const previousEffects = [...previous.match(/CHECK \(effect IN \(([^)]+)\)/)[1].matchAll(/'([^']+)'/g)].map((match) => match[1]);
  const effects = [...new Set([...previousEffects, ...KQ_CARDS.map((card) => card.effect)])].sort();
  const payload = KQ_CARDS.map((card) => ({
    code: card.code, name: card.name, description: card.description, image_url: getKqCardArtwork(card.code),
    category: card.category, timing: card.timing, effect: card.effect, xp_cost: card.xpCost,
    tags: card.tags, targets: card.targets ?? [], advantage: getKqCardTradeoff(card).benefit, drawback: getKqCardTradeoff(card).risk,
  }));
  const json = JSON.stringify(payload, null, 2);
  const migration = `-- Generated by scripts/generate-placard-indoor-catalog.mjs.
-- Same definition IDs, ownership, rarity and pack odds. No card instance is removed.
BEGIN;
CREATE TEMP TABLE kq_indoor_deck_update ON COMMIT DROP AS
SELECT * FROM jsonb_to_recordset($deck$${json}$deck$::jsonb)
AS card(code text, name text, description text, image_url text, category text, timing text,
  effect text, xp_cost smallint, tags text[], targets text[], advantage text, drawback text);

DO $$ BEGIN
  IF (SELECT count(*) FROM public.lottery_card_definitions d JOIN kq_indoor_deck_update u USING (code)) <> 32
    OR (SELECT count(*) FROM public.kq_support_card_rules r JOIN public.lottery_card_definitions d ON d.id = r.card_definition_id JOIN kq_indoor_deck_update u USING (code)) <> 32 THEN
    RAISE EXCEPTION 'indoor_deck_catalog_incomplete';
  END IF;
END $$;

ALTER TABLE public.kq_support_card_rules DROP CONSTRAINT IF EXISTS kq_support_card_rules_effect_check;
ALTER TABLE public.kq_support_card_rules ADD CONSTRAINT kq_support_card_rules_effect_check
CHECK (effect IN (${effects.map((effect) => `'${effect}'`).join(", ")}));

UPDATE public.lottery_card_definitions d
SET name = u.name, description = u.description, image_url = u.image_url, updated_at = now()
FROM kq_indoor_deck_update u WHERE d.code = u.code;

UPDATE public.kq_support_card_rules r
SET category = u.category, timing = u.timing, effect = u.effect, xp_cost = u.xp_cost,
  tags = u.tags, targets = u.targets, advantage = u.advantage, drawback = u.drawback,
  rules_version = r.rules_version + 1, updated_at = now()
FROM kq_indoor_deck_update u JOIN public.lottery_card_definitions d USING (code)
WHERE r.card_definition_id = d.id;
COMMIT;
`;
  await writeFile("supabase/migrations/20260913000600_kq_indoor_deck_redesign.sql", migration);
  console.log(`Catalogue indoor : ${payload.length} cartes, aucune modification des exemplaires possédés.`);
} finally { await vite.close(); }
